// Command notices writes THIRD_PARTY_NOTICES.md: the licences of every Go
// module compiled into SheetDiver (desktop and headless builds), every
// npm package shipped in its UI, and PDFium with the libraries compiled
// into its WebAssembly build. Release archives include the file.
//
//	go run ./scripts/notices            (or: make notices)
//
// It fails when a dependency has no licence file, so a new dependency
// can't ship without its notice.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// licenseNames are the files that hold a package's licence.
var licenseNames = []string{"LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENSE-MIT", "COPYING", "COPYING.md", "NOTICE", "NOTICE.md", "NOTICE.txt", "license", "license.md", "LICENSE.APACHE2", "LICENSE.BSD"}

// dep is one third-party component.
type dep struct {
	name, version, license string
	texts                  []text
}

// text is one licence file.
type text struct{ file, body string }

// main writes the notices file.
func main() {
	out := flag("-o", "THIRD_PARTY_NOTICES.md")
	goDeps, err := goModules()
	if err != nil {
		log.Fatal(err)
	}
	npmDeps, err := npmPackages("frontend")
	if err != nil {
		log.Fatal(err)
	}
	var missing []string
	for _, d := range append(goDeps, npmDeps...) {
		if len(d.texts) == 0 {
			missing = append(missing, d.name+"@"+d.version)
		}
	}
	if len(missing) > 0 {
		log.Fatalf("no licence file for: %s", strings.Join(missing, ", "))
	}
	var b bytes.Buffer
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("SheetDiver is MIT licensed (see LICENSE). Its binaries include the third-party software below; each is used under the licence that follows it.\n")
	b.WriteString("This file is generated by `make notices` (scripts/notices); don't edit it by hand.\n\n")
	b.WriteString("- [PDFium](#pdfium) and the libraries compiled into its WebAssembly build\n")
	fmt.Fprintf(&b, "- [Go modules](#go-modules) (%d)\n", len(goDeps))
	fmt.Fprintf(&b, "- [npm packages](#npm-packages) (%d)\n\n", len(npmDeps))

	b.WriteString("## PDFium\n\n")
	b.WriteString("PDF reading uses PDFium (https://pdfium.googlesource.com/pdfium/) compiled to WebAssembly by pdfium-binaries (https://github.com/bblanchon/pdfium-binaries, chromium/8057) and embedded by go-pdfium. It includes the libraries below.\n\n")
	files, err := filepath.Glob("packaging/licenses/pdfium/*")
	if err != nil || len(files) == 0 {
		log.Fatal("packaging/licenses/pdfium is missing")
	}
	sort.Strings(files)
	for _, f := range files {
		body, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		fmt.Fprintf(&b, "### %s\n\n", strings.TrimSuffix(filepath.Base(f), filepath.Ext(f)))
		fence(&b, string(body))
	}

	section := func(title string, deps []dep) {
		fmt.Fprintf(&b, "## %s\n\n", title)
		for _, d := range deps {
			fmt.Fprintf(&b, "### %s %s\n\n", d.name, d.version)
			if d.license != "" {
				fmt.Fprintf(&b, "Licence: %s\n\n", d.license)
			}
			for _, t := range d.texts {
				if len(d.texts) > 1 {
					fmt.Fprintf(&b, "%s:\n\n", t.file)
				}
				fence(&b, t.body)
			}
		}
	}
	section("Go modules", goDeps)
	section("npm packages", npmDeps)
	if err := os.WriteFile(out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s: PDFium (%d files), %d Go modules, %d npm packages", out, len(files), len(goDeps), len(npmDeps))
}

// flag returns the value after name in the arguments, else def.
func flag(name, def string) string {
	for i, a := range os.Args[1:] {
		if a == name && i+2 < len(os.Args) {
			return os.Args[i+2]
		}
	}
	return def
}

// fence writes text in a fenced block long enough not to collide with it.
func fence(b *bytes.Buffer, s string) {
	f := "```"
	for strings.Contains(s, f) {
		f += "`"
	}
	fmt.Fprintf(b, "%stext\n%s\n%s\n\n", f, strings.TrimRight(strings.ReplaceAll(s, "\r\n", "\n"), "\n"), f)
}

// licenseTexts reads the licence files at the top of dir.
func licenseTexts(dir string) []text {
	var out []text
	seen := map[string]bool{}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	for _, want := range licenseNames {
		for _, e := range entries {
			if e.IsDir() || !strings.EqualFold(e.Name(), want) || seen[strings.ToLower(e.Name())] {
				continue
			}
			body, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err == nil && len(bytes.TrimSpace(body)) > 0 {
				out = append(out, text{e.Name(), string(body)})
				seen[strings.ToLower(e.Name())] = true
			}
		}
	}
	return out
}

// goModules lists the modules compiled into the desktop and headless
// builds of every target OS.
func goModules() ([]dep, error) {
	mods := map[string]dep{}
	for _, goos := range []string{"linux", "darwin", "windows"} {
		for _, tags := range []string{"webkit2_41", "nogui"} {
			cmd := exec.Command("go", "list", "-deps", "-tags", tags, "-f", `{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}{{end}}`, ".")
			cmd.Env = append(os.Environ(), "GOOS="+goos, "CGO_ENABLED=1")
			cmd.Stderr = os.Stderr
			b, err := cmd.Output()
			if err != nil {
				return nil, fmt.Errorf("go list (%s, %s): %w", goos, tags, err)
			}
			for _, line := range strings.Split(strings.TrimSpace(string(b)), "\n") {
				p := strings.SplitN(line, "|", 3)
				if len(p) != 3 || p[0] == "" {
					continue
				}
				if _, ok := mods[p[0]]; !ok {
					mods[p[0]] = dep{name: p[0], version: p[1], texts: licenseTexts(p[2])}
				}
			}
		}
	}
	var out []dep
	for _, d := range mods {
		out = append(out, d)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out, nil
}

// pkgJSON is the part of package.json read here.
type pkgJSON struct {
	Name         string            `json:"name"`
	Version      string            `json:"version"`
	License      any               `json:"license"`
	Dependencies map[string]string `json:"dependencies"`
}

// npmPackages lists the production dependencies of the frontend,
// transitively, from node_modules.
func npmPackages(root string) ([]dep, error) {
	var top pkgJSON
	if err := readJSON(filepath.Join(root, "package.json"), &top); err != nil {
		return nil, err
	}
	seen := map[string]dep{}
	var walk func(name, from string) error
	walk = func(name, from string) error {
		dir := resolve(root, from, name)
		if dir == "" {
			return fmt.Errorf("npm package %s isn't installed (run npm ci in frontend)", name)
		}
		var p pkgJSON
		if err := readJSON(filepath.Join(dir, "package.json"), &p); err != nil {
			return err
		}
		key := p.Name + "@" + p.Version
		if _, ok := seen[key]; ok {
			return nil
		}
		seen[key] = dep{name: p.Name, version: p.Version, license: licenseString(p.License), texts: licenseTexts(dir)}
		for d := range p.Dependencies {
			if err := walk(d, dir); err != nil {
				return err
			}
		}
		return nil
	}
	for d := range top.Dependencies {
		if err := walk(d, root); err != nil {
			return nil, err
		}
	}
	var out []dep
	for _, d := range seen {
		out = append(out, d)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out, nil
}

// resolve finds an npm package the way Node does: in node_modules of
// from and its parents, up to root.
func resolve(root, from, name string) string {
	abs, _ := filepath.Abs(root)
	for dir, _ := filepath.Abs(from); ; dir = filepath.Dir(dir) {
		p := filepath.Join(dir, "node_modules", name)
		if st, err := os.Stat(filepath.Join(p, "package.json")); err == nil && !st.IsDir() {
			return p
		}
		if dir == abs || dir == filepath.Dir(dir) {
			return ""
		}
	}
}

// readJSON decodes a JSON file.
func readJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}

// licenseString renders package.json's license field.
func licenseString(v any) string {
	switch l := v.(type) {
	case string:
		return l
	case map[string]any:
		if t, ok := l["type"].(string); ok {
			return t
		}
	}
	return ""
}
