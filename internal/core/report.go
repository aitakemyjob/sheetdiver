// reportKeys are the key parameters shown per part in a report, by
// category (others show their first few comparison keys).
var reportKeys = map[string][]string{
	"buck":       {"vin", "iout", "fsw", "iq"},
	"boost":      {"vin", "iout", "ilim", "fsw"},
	"buck-boost": {"vin", "vout", "iout", "ilim"},
	"ldo":        {"vin", "iout", "vdropout", "iq"},
	"mosfet-n":   {"vds", "id", "rdson", "vgs_th"},
	"mosfet-p":   {"vds", "id", "rdson", "vgs_th"},
	"mosfet":     {"vds", "id", "rdson", "vgs_th"},
	"charger":    {"vin", "ichg", "vreg"},
}

// ProjectReport renders a project as a Markdown design-review document:
// summary, findings, rails and power budget, parts with their key
// parameters and status, saved calculations and notes.
func (s *Service) ProjectReport(ctx context.Context, name string) (string, error) {
	d, err := s.ProjectDetail(ctx, name)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	p := d.Project
	fmt.Fprintf(&b, "# %s — design review\n\n", p.Name)
	if p.Description != "" {
		b.WriteString(p.Description + "\n\n")
	}
	counts := map[string]int{}
	for _, c := range d.Checks {
		counts[c.Level]++
	}
	qty := 0
	for _, pp := range d.Parts {
		qty += pp.Qty
	}
	fmt.Fprintf(&b, "Generated by SheetDiver %s on %s. %d BOM lines (%d parts), %d rails, input power %s at maximum load.\n\n",
		s.Version, time.Now().Format("2006-01-02"), len(d.Parts), qty, len(d.Rails), calc.Eng(d.InputPower, "W"))
	fmt.Fprintf(&b, "**Checks:** %d errors, %d warnings, %d passed.\n\n", counts[calc.Error], counts[calc.Warn], counts[calc.OK])

	b.WriteString("## Findings\n\n")
	if counts[calc.Error]+counts[calc.Warn] == 0 {
		b.WriteString("No errors or warnings.\n\n")
	}
	for _, level := range []string{calc.Error, calc.Warn} {
		for _, c := range d.Checks {
			if c.Level != level {
				continue
			}
			tag := "⚠️ Warning"
			if level == calc.Error {
				tag = "❌ Error"
			}
			where := strings.Trim(strings.Join([]string{c.Part, c.Rail}, " · "), " ·")
			if where != "" {
				where = " (" + where + ")"
			}
			fmt.Fprintf(&b, "- **%s**%s: %s\n", tag, where, mdCell(c.Message))
		}
	}
	if counts[calc.OK] > 0 {
		b.WriteString("\n<details><summary>Passed checks</summary>\n\n")
		for _, c := range d.Checks {
			if c.Level == calc.OK {
				fmt.Fprintf(&b, "- ✅ %s\n", mdCell(c.Message))
			}
		}
		b.WriteString("\n</details>\n")
	}
	b.WriteString("\n")

	if len(d.Rails) > 0 {
		b.WriteString("## Rails\n\n| Rail | Voltage | Source | Load typ | Load max | Capacity | Use | Power | Ripple budget | Feeds |\n|---|---|---|---:|---:|---|---:|---:|---|---|\n")
		for _, r := range d.Rails {
			capTxt, use := "–", "–"
			switch {
			case r.Capacity > 0:
				capTxt = calc.Eng(r.Capacity, "A") + " (" + r.CapacityFrom + ")"
				use = fmt.Sprintf("%.0f%%", 100*r.LoadMax/r.Capacity)
			case r.Ceiling > 0:
				capTxt = "unknown; limit " + calc.Eng(r.Ceiling, "A")
			}
			ripple := "–"
			if r.Ripple != nil {
				ripple = calc.Eng(*r.Ripple, "V") + " p-p (" + r.RippleLimit + ")"
			}
			feeds := r.Consumers
			if r.OtherMax != nil || r.OtherTyp != nil {
				feeds = append(append([]string(nil), feeds...), "other loads "+calc.Eng(firstPositive(r.OtherMax, r.OtherTyp), "A"))
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", mdCell(r.Name), railVoltage(r.Rail), mdCell(firstNonEmpty(r.SourcePart, r.Source, "external")),
				calc.Eng(r.LoadTyp, "A"), calc.Eng(r.LoadMax, "A"), mdCell(capTxt), use, calc.Eng(r.Power, "W"), mdCell(ripple), mdCell(strings.Join(feeds, ", ")))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Parts\n\n")
	if len(d.Parts) == 0 {
		b.WriteString("No parts yet.\n\n")
	} else {
		b.WriteString("| Ref | Qty | Part | Manufacturer | Type | Status | Supply → output | Key parameters | Datasheet |\n|---|---:|---|---|---|---|---|---|---|\n")
		for _, pp := range d.Parts {
			part, _ := s.Lib.PartByID(ctx, pp.PartID)
			mpn := pp.MPN
			if pp.Variant != "" {
				mpn += " (" + pp.Variant + ")"
			}
			status := pp.Status
			if part.Favorite {
				status = strings.TrimSpace("★ " + status)
			}
			rails := pp.SupplyRail
			if pp.OutputRail != "" {
				rails += " → " + pp.OutputRail
			}
			ds := "none"
			if part.DatasheetID != 0 {
				if sheet, err := s.Lib.Datasheet(ctx, part.DatasheetID); err == nil {
					ds = sheet.Filename
					if strings.HasPrefix(sheet.SourceURL, "http") {
						ds = fmt.Sprintf("[%s](%s)", sheet.Filename, sheet.SourceURL)
					}
				}
			}
			fmt.Fprintf(&b, "| %s | %d | %s | %s | %s | %s | %s | %s | %s |\n", mdCell(pp.Designator), pp.Qty, mdCell(mpn), mdCell(part.Manufacturer), mdCell(pp.Category),
				mdCell(status), mdCell(rails), mdCell(s.keySummary(ctx, part)), ds)
		}
		b.WriteString("\n")
	}

	writeConnections(&b, d.Connections)

	if len(d.Calculations) > 0 {
		b.WriteString("## Calculations\n\n")
		for _, c := range d.Calculations {
			fmt.Fprintf(&b, "### %s\n\n", c.Title)
			var resp CalcResponse
			if json.Unmarshal(c.Outputs, &resp) != nil {
				b.WriteString("(unreadable)\n\n")
				continue
			}
			if resp.Result.Summary != "" {
				b.WriteString(resp.Result.Summary + "\n\n")
			}
			if len(resp.Inputs) > 0 {
				var ks []string
				for k := range resp.Inputs {
					ks = append(ks, k)
				}
				sort.Strings(ks)
				var in []string
				for _, k := range ks {
					in = append(in, fmt.Sprintf("%s = %v", k, resp.Inputs[k]))
				}
				fmt.Fprintf(&b, "Inputs: %s\n\n", strings.Join(in, ", "))
			}
			if len(resp.Result.Outputs) > 0 {
				b.WriteString("| Output | Value | Formula |\n|---|---:|---|\n")
				for _, o := range resp.Result.Outputs {
					fmt.Fprintf(&b, "| %s | %s | %s |\n", mdCell(o.Name), calc.Eng(o.Value, o.Unit), mdCell(o.Formula))
				}
				b.WriteString("\n")
			}
			for _, ch := range resp.Result.Checks {
				if ch.Level != calc.OK {
					fmt.Fprintf(&b, "- **%s:** %s\n", ch.Level, mdCell(ch.Message))
				}
			}
			for _, sg := range resp.Result.Suggestions {
				fmt.Fprintf(&b, "- %s\n", mdCell(sg))
			}
			b.WriteString("\n")
		}
	}

	if len(d.Notes) > 0 {
		b.WriteString("## Notes\n\n")
		for _, n := range d.Notes {
			fmt.Fprintf(&b, "- %s (%s, %s)\n", strings.ReplaceAll(strings.TrimSpace(n.Body), "\n", "\n  "), n.Author, n.CreatedAt.Format("2006-01-02"))
		}
		b.WriteString("\n")
	}
	return b.String(), nil
}

// keySummary renders a part's main parameters on one line, such as
// "vin 4.5 V … 17 V · iout ≤ 3 A".
func (s *Service) keySummary(ctx context.Context, p library.Part) string {
	vals, err := s.partValues(ctx, p)
	if err != nil || len(vals) == 0 {
		return ""
	}
	keys := reportKeys[p.Category]
	if keys == nil {
		keys = categoryKeys[p.Category]
	}
	var out []string
	for _, k := range keys {
		if v, ok := vals[k]; ok {
			out = append(out, k+" "+rangeStr(v, true))
		}
		if len(out) == 4 {
			break
		}
	}
	return strings.Join(out, " · ")
}

// railVoltage renders a rail's voltage: nominal with its range.
func railVoltage(r library.Rail) string {
	switch {
	case r.VNom != nil && r.VMin != nil && r.VMax != nil:
		return fmt.Sprintf("%s (%s … %s)", calc.Eng(*r.VNom, "V"), calc.Eng(*r.VMin, "V"), calc.Eng(*r.VMax, "V"))
	case r.VNom != nil:
		return calc.Eng(*r.VNom, "V")
	case r.VMin != nil && r.VMax != nil:
		return calc.Eng(*r.VMin, "V") + " … " + calc.Eng(*r.VMax, "V")
	}
	return "–"
}

// mdCell escapes text for a Markdown table cell.
func mdCell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.Join(strings.Fields(s), " ")
}

// writeConnections adds the block diagram (as a Mermaid flowchart, which
// GitHub and most Markdown viewers draw) and the connection table.
func writeConnections(b *strings.Builder, c Connections) {
	if len(c.Connections) == 0 {
		return
	}
	if len(c.Diagram.Links) > 0 {
		b.WriteString("## Block diagram\n\n```mermaid\nflowchart LR\n")
		ids := map[string]string{}
		for i, p := range c.Diagram.Parts {
			ids[p.ID] = fmt.Sprintf("n%d", i)
		}
		node := func(p DiagramPart, indent string) {
			label := strings.ReplaceAll(p.Title, `"`, "'")
			if p.Kind == "connector" {
				fmt.Fprintf(b, "%s%s([\"%s\"])\n", indent, ids[p.ID], label)
			} else {
				fmt.Fprintf(b, "%s%s[\"%s\"]\n", indent, ids[p.ID], label)
			}
		}
		for _, p := range c.Diagram.Parts {
			if p.Group == "" {
				node(p, "  ")
			}
		}
		// Each group as a subgraph around its parts.
		for i, g := range c.Diagram.Groups {
			fmt.Fprintf(b, "  subgraph g%d[\"%s\"]\n", i, strings.ReplaceAll(g.Name, `"`, "'"))
			for _, p := range c.Diagram.Parts {
				if strings.EqualFold(p.Group, g.Name) {
					node(p, "    ")
				}
			}
			b.WriteString("  end\n")
		}
		for _, e := range c.Diagram.Links {
			arrow := "---"
			if e.Kind == "power" {
				arrow = "==>"
			}
			fmt.Fprintf(b, "  %s %s|\"%s\"| %s\n", ids[e.From], arrow, strings.ReplaceAll(e.Label, `"`, "'"), ids[e.To])
		}
		b.WriteString("```\n\n")
	}
	if len(c.Connections) > 0 {
		b.WriteString("## Connections\n\n| Net | Kind | Connected to |\n|---|---|---|\n")
		kind := map[string]string{}
		for _, n := range c.Nets {
			k := n.Kind
			if n.Bus != "" {
				k += " (" + n.Bus + ")"
			}
			kind[strings.ToLower(n.Name)] = k
		}
		for i := 0; i < len(c.Connections); {
			net := c.Connections[i].Net
			var ends []string
			for ; i < len(c.Connections) && c.Connections[i].Net == net; i++ {
				r := c.Connections[i]
				end := r.Endpoint
				if r.Pin != "" {
					end += "." + r.Pin
					if r.PinName != "" && r.PinName != r.Pin {
						end += " (" + r.PinName + ")"
					}
				}
				ends = append(ends, end)
			}
			fmt.Fprintf(b, "| %s | %s | %s |\n", mdCell(net), mdCell(kind[strings.ToLower(net)]), mdCell(strings.Join(ends, ", ")))
		}
		b.WriteString("\n")
	}
	for _, po := range c.Pinouts {
		fmt.Fprintf(b, "### %s pins\n\n| Pin | Name | Net | Connected to |\n|---|---|---|---|\n", po.Title)
		for _, p := range po.Pins {
			net := p.Net
			if net == "" {
				net = "not connected"
			}
			fmt.Fprintf(b, "| %s | %s | %s | %s |\n", mdCell(p.Number), mdCell(p.Name), mdCell(net), mdCell(strings.Join(p.To, ", ")))
		}
		b.WriteString("\n")
	}
}
